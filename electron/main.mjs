function createWindow() {
  mainWindow = new BrowserWindow({
    width: 1200,
    height: 800,
    webPreferences: {
      preload: join(__dirname, "preload.mjs"),
      contextIsolation: true,
      nodeIntegration: false,
    },
    title: "QubaBot",
    icon: APP_ICON,
  });

  mainWindow.loadURL(`http://localhost:5199`);

  mainWindow.on("closed", () => {
    mainWindow = null;
  });
}